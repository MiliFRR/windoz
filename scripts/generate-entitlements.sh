#!/usr/bin/env bash
# Generate (or verify) app-windoz/Config/Windoz.entitlements.
#
# One source of truth for the signing entitlements. CI runs
# `generate-entitlements.sh --check` so the committed plist can never drift
# from what this script says it should be.
#
# The CI build is unsigned; this plist documents the target set for any
# signing profile that can grant it (see the comments inside).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="$ROOT/app-windoz/Config/Windoz.entitlements"

generate() {
  cat <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<!--
	  windoz signing entitlements.

	  This file is generated by scripts/generate-entitlements.sh (verified in
	  CI with --check), so edit the script, not this file.

	  The CI build is unsigned (CODE_SIGNING_ALLOWED=NO); the sideloading tool
	  on your machine signs the IPA and applies its own entitlements to it.
	  This plist is the documented set windoz needs from a signing profile
	  that can grant it:

	    get-task-allow ...... lets a debugger attach; on iOS 17+ that is what
	                          actually sets CS_DEBUGGED and lets FEX-Emu's
	                          generated code run (JIT via StikDebug).
	    dynamic-codesigning . the entitlement the sideload scene calls
	                          "memory+"/JIT; harmless when a profile cannot
	                          grant it, and correct when one can.

	  Deliberately NOT here: the increased-memory limit. That is a separate
	  entitlement a free Apple ID profile cannot grant, so the app probes it
	  at run time and reports it honestly as unavailable (Settings -> Memory)
	  instead of promising it from a plist.
	-->
	<key>get-task-allow</key>
	<true/>
	<key>dynamic-codesigning</key>
	<true/>
</dict>
</plist>
PLIST
}

if [ "${1:-}" = "--check" ]; then
  TMP="$(mktemp)"
  trap 'rm -f "$TMP"' EXIT
  generate > "$TMP"
  if diff -u "$DEST" "$TMP"; then
    echo "entitlements: up to date ($DEST)"
  else
    echo "ERROR: $DEST is stale; run scripts/generate-entitlements.sh" >&2
    exit 1
  fi
else
  generate > "$DEST"
  echo "wrote $DEST"
  plutil -lint "$DEST" 2>/dev/null || true
fi
